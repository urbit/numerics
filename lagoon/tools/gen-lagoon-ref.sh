#!/bin/sh
#  Regenerate desk/lib/lagoon-ref.hoon from desk/lib/lagoon.hoon.
#
#  lagoon-ref is /lib/lagoon with every ~% and ~/ hint commented out.
#  Vere matches lagoon jets by hint label, so the copy never reaches a
#  jet; /tests/lib/lagoon-pathological uses it as the unjetted
#  reference.  Rerun this after every change to /lib/lagoon.
set -eu
cd "$(dirname "$0")/../desk/lib"
{
  printf '::  GENERATED by lagoon/tools/gen-lagoon-ref.sh -- do not edit.\n'
  printf '::  /lib/lagoon without jet hints: the test reference, not shipped.\n'
  sed -e 's/^\( *\)~\/  %\([a-z0-9-]*\)$/\1::  (unjetted reference) %\2/' \
      -e 's/^~%  %non  \.\.part  ~/::  (unjetted reference: no ~% hint)/' \
      lagoon.hoon
} > lagoon-ref.hoon
if grep -nE '^[^:]*~[%/]  ' lagoon-ref.hoon; then
  echo 'gen-lagoon-ref: a jet hint survived' >&2
  exit 1
fi
